#!/usr/bin/env bash
# ArtCraft Android Unified Test & Quality Gate Runner
# Runs bash/python syntax checks, all unit tests, and upstream release audits.

set -Eeuo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

# Formatting helpers
if [[ -t 1 && -z "${NO_COLOR:-}" ]]; then
    BOLD="\033[1m"
    GREEN="\033[1;32m"
    RED="\033[1;31m"
    YELLOW="\033[1;33m"
    BLUE="\033[1;34m"
    RESET="\033[0m"
else
    BOLD=""
    GREEN=""
    RED=""
    YELLOW=""
    BLUE=""
    RESET=""
fi

MODE="standard"
VERBOSE=false

usage() {
    cat <<EOF
Usage: scripts/test_all.sh [OPTIONS]

Unified quality gate and testing runner for ArtCraft Android.

Options:
  -q, --quick         Run syntax checks and unit tests only (skips network release audit)
  -s, --strict        Run full checks with strict release tag verification
  -v, --verbose       Show verbose diagnostic output
  --install-hook      Install this script as a Git pre-commit hook (.git/hooks/pre-commit)
  -h, --help          Show this help message
EOF
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        -q|--quick)
            MODE="quick"
            shift
            ;;
        -s|--strict)
            MODE="strict"
            shift
            ;;
        -v|--verbose)
            VERBOSE=true
            shift
            ;;
        --install-hook)
            HOOK_FILE="$ROOT/.git/hooks/pre-commit"
            mkdir -p "$ROOT/.git/hooks"
            cat > "$HOOK_FILE" <<'HOOK'
#!/usr/bin/env bash
# Pre-commit hook generated by scripts/test_all.sh
set -e
ROOT="$(git rev-parse --show-toplevel)"
echo "Running ArtCraft Android pre-commit checks..."
bash "$ROOT/scripts/test_all.sh" --quick
HOOK
            chmod +x "$HOOK_FILE"
            printf "${GREEN}✔ Successfully installed pre-commit hook in .git/hooks/pre-commit${RESET}\n"
            exit 0
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            echo "Unknown option: $1" >&2
            usage
            exit 1
            ;;
    esac
done

START_TIME="$(date +%s)"
TOTAL_STEPS=4
if [[ "$MODE" == "quick" ]]; then
    TOTAL_STEPS=3
fi

STEP=1
step() {
    printf "\n${BOLD}${BLUE}[%d/%d] %s${RESET}\n" "$STEP" "$TOTAL_STEPS" "$1"
    STEP=$((STEP + 1))
}

printf "${BOLD}================================================================================${RESET}\n"
printf "${BOLD}ArtCraft Android Quality Gate & Test Runner (${MODE} mode)${RESET}\n"
printf "${BOLD}================================================================================${RESET}\n"

# 1. Shell syntax verification
step "Verifying Bash script syntax (bash -n)..."
SH_ERRORS=0
while IFS= read -r sh_file; do
    if ! bash -n "$sh_file"; then
        printf "${RED}✘ Syntax error in %s${RESET}\n" "$sh_file"
        SH_ERRORS=$((SH_ERRORS + 1))
    fi
done < <(find build.sh build-debug.sh build-launcher.sh clean.sh lib/ scripts/ adapters/ -type f -name "*.sh" 2>/dev/null | sort)

if (( SH_ERRORS > 0 )); then
    printf "${RED}✘ Shell script verification failed with %d error(s).${RESET}\n" "$SH_ERRORS"
    exit 1
fi
printf "${GREEN}✔ All Shell scripts passed syntax validation.${RESET}\n"

# 2. Python syntax verification
step "Compiling Python scripts (py_compile)..."
PY_ERRORS=0
while IFS= read -r py_file; do
    if ! python3 -m py_compile "$py_file"; then
        printf "${RED}✘ Compilation error in %s${RESET}\n" "$py_file"
        PY_ERRORS=$((PY_ERRORS + 1))
    fi
done < <(find lib/ scripts/ test/ -type f -name "*.py" 2>/dev/null | sort)

if (( PY_ERRORS > 0 )); then
    printf "${RED}✘ Python compilation failed with %d error(s).${RESET}\n" "$PY_ERRORS"
    exit 1
fi
printf "${GREEN}✔ All Python scripts compiled cleanly.${RESET}\n"

# 3. Unit test suite
step "Running Unit Test Suite (python3 -m unittest)..."
TEST_ARGS=("-m" "unittest" "discover" "-s" "test" "-p" "test_*.py")
if [[ "$VERBOSE" == "true" ]]; then
    TEST_ARGS+=("-v")
fi

if ! python3 "${TEST_ARGS[@]}"; then
    printf "${RED}✘ Unit tests failed.${RESET}\n"
    exit 1
fi
printf "${GREEN}✔ All unit tests passed.${RESET}\n"

# 4. Host-side platform hardware tests
if command -v rustc &>/dev/null && [[ -f "test/android_device_kind.rs" ]]; then
    step "Running Host Platform Hardware Tests (test/android_device_kind.rs)..."
    TMP_TEST=$(mktemp /tmp/device_kind_test.XXXXXX)
    if rustc --edition 2021 --test test/android_device_kind.rs -o "$TMP_TEST" 2>/dev/null && "$TMP_TEST" --quiet; then
        rm -f "$TMP_TEST"
        printf "${GREEN}✔ Host platform device kind tests passed.${RESET}\n"
    else
        rm -f "$TMP_TEST"
        printf "${RED}✘ Host platform device kind tests failed.${RESET}\n"
        exit 1
    fi
fi

# 5. Release sync audit
if [[ "$MODE" != "quick" ]]; then
    step "Auditing Upstream Releases & Tags (test/check_releases.py)..."
    CHECK_ARGS=("test/check_releases.py")
    if [[ "$MODE" == "strict" ]]; then
        CHECK_ARGS+=("--strict")
    fi
    if [[ "$VERBOSE" == "true" ]]; then
        CHECK_ARGS+=("-v")
    fi

    if ! python3 "${CHECK_ARGS[@]}"; then
        printf "${RED}✘ Upstream release audit failed.${RESET}\n"
        exit 1
    fi
    printf "${GREEN}✔ Upstream release audit passed.${RESET}\n"
fi

END_TIME="$(date +%s)"
ELAPSED=$((END_TIME - START_TIME))

printf "\n${BOLD}================================================================================${RESET}\n"
printf "${BOLD}${GREEN}✔ All quality gates and tests passed in %ds!${RESET}\n" "$ELAPSED"
printf "${BOLD}================================================================================${RESET}\n"
exit 0
