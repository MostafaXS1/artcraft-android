#!/usr/bin/env python3
"""Generate the Gradle half of an app's Android build.

Reads the launcher crate's ``[package.metadata.android]`` tables — the same TOML cargo-apk2
used to read — out of ``<android_dir>/Cargo.toml`` and writes, on every build:

* ``<android_dir>/AndroidManifest.xml`` — package, permissions, application/activity entries,
  the MAIN/LAUNCHER filter and the app's file-association filters, one to one with the
  metadata. The ``package`` attribute is gone (AGP 8 sets the namespace in build.gradle) and
  so is ``<uses-sdk>`` (defaultConfig owns minSdk/targetSdk).
* ``<android_dir>/res/values/themes.xml`` — the ``Theme.Artcraft`` style the manifest
  references. GameActivity extends AppCompatActivity, which refuses to inflate under a
  framework-only theme ("You need to use a Theme.AppCompat theme"), so the parent is
  AppCompat; ``windowFullscreen`` carries over from the old
  ``Theme.DeviceDefault.NoActionBar.Fullscreen`` (the edge-to-edge Java code builds on that
  flag), and the black window background is the first frame before egui draws.
* ``<android_dir>/android/`` — a single-module Gradle project (settings.gradle, build.gradle,
  gradle.properties, the wrapper copied from ``templates/gradle/``). Its sourceSets point one
  level up at the java/res/jniLibs trees cargo-ndk and the launcher generator produced.
* ``<android_dir>/.artcraft-gradle.properties`` — ``MIN_SDK`` for cargo-ndk's ``--platform``.

The versionCode mirrors ndk-build2's ``VersionCode::from_semver(...).to_code(1)`` so the
Updater keeps accepting upgrades from the cargo-apk era: ``((1 << 24) | major << 16 |
minor << 8 | patch)`` of the app's own semver core.
"""

import re
import shutil
import stat
import sys
import tomllib
import xml.sax.saxutils
from pathlib import Path

GRADLE_PLUGIN_VERSION = "8.7.3"

# snake_case metadata key -> android: attribute, for the parts of ndk-build2's Activity and
# IntentFilter structs the builder's launchers actually use.
ACTIVITY_ATTRS = (
    ("label", "android:label"),
    ("launch_mode", "android:launchMode"),
    ("orientation", "android:screenOrientation"),
    ("config_changes", "android:configChanges"),
    ("window_soft_input_mode", "android:windowSoftInputMode"),
    ("resizeable_activity", "android:resizeableActivity"),
    ("always_retain_task_state", "android:alwaysRetainTaskState"),
)
DATA_ATTRS = (
    ("scheme", "android:scheme"),
    ("host", "android:host"),
    ("port", "android:port"),
    ("path", "android:path"),
    ("path_pattern", "android:pathPattern"),
    ("path_prefix", "android:pathPrefix"),
    ("mime_type", "android:mimeType"),
)

THEMES_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by artcraft-android-builder. GameActivity (androidx.games:games-activity)
     extends AppCompatActivity, which only inflates under a Theme.AppCompat descendant;
     windowFullscreen keeps the flag the old framework-only theme carried, and black is the
     first frame before the Rust UI draws. -->
<resources>
    <style name="Theme.Artcraft" parent="Theme.AppCompat.NoActionBar">
        <item name="android:windowFullscreen">true</item>
        <item name="android:windowBackground">@android:color/black</item>
    </style>
</resources>
"""

GRADLE_PROPERTIES = """org.gradle.jvmargs=-Xmx2g -Dfile.encoding=UTF-8
android.useAndroidX=true
android.nonTransitiveRClass=true
"""


def _esc(value):
    """Escape a value for use inside an XML attribute (quotes included)."""
    return xml.sax.saxutils.escape(str(value), {'"': "&quot;"})


def _groovy(value):
    """Escape a value for a Groovy single-quoted string literal."""
    return str(value).replace("\\", "\\\\").replace("'", "\\'")


def _as_list(value):
    """The metadata tables cargo-apk2 accepted both as one table and as an array of tables."""
    if value is None:
        return []
    if isinstance(value, dict):
        return [value]
    return list(value)


def version_code(version):
    """ndk-build2's ``VersionCode::from_semver(version).to_code(1)``.

    ``from_semver`` splits on ``.``, ``-`` and ``+`` and parses the first three components as
    integers; anything else is an error, as it was with cargo-apk2.
    """
    components = re.split(r"[.+-]", version)
    if len(components) < 3:
        raise SystemExit(
            f"Cannot derive a versionCode from {version!r}: expected MAJOR.MINOR.PATCH."
        )
    try:
        major, minor, patch = (int(component) for component in components[:3])
    except ValueError:
        raise SystemExit(
            f"Cannot derive a versionCode from {version!r}: components must be numbers."
        ) from None
    return (1 << 24) | (major << 16) | (minor << 8) | patch


def manifest_xml(android_meta):
    """Render AndroidManifest.xml from ``[package.metadata.android]``."""
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<manifest xmlns:android="http://schemas.android.com/apk/res/android">',
    ]
    for permission in _as_list(android_meta.get("uses_permission")):
        attrs = f'android:name="{_esc(permission["name"])}"'
        if permission.get("max_sdk_version") is not None:
            attrs += f' android:maxSdkVersion="{_esc(permission["max_sdk_version"])}"'
        lines.append(f"    <uses-permission {attrs} />")

    application = android_meta.get("application") or {}
    app_attrs = [
        f'{attr}="{_esc(application[key])}"'
        for key, attr in (("label", "android:label"), ("theme", "android:theme"), ("icon", "android:icon"))
        if application.get(key)
    ]
    lines.append(f'    <application {" ".join(app_attrs)}>')

    activities = _as_list(application.get("activity")) or [{}]
    for activity in activities:
        # ndk-build2 defaults the name to "" (an unset android:name); every app the builder
        # ships names its Activity, so this only mirrors the default for completeness.
        attrs = [f'android:name="{_esc(activity.get("name", ""))}"']
        for key, attr in ACTIVITY_ATTRS:
            if activity.get(key) is not None:
                attrs.append(f'{attr}="{_esc(activity[key])}"')
        if activity.get("exported") is not None:
            attrs.append(f'android:exported="{"true" if activity["exported"] else "false"}"')
        lines.append(f'        <activity {" ".join(attrs)}>')

        for meta in _as_list(activity.get("meta_data")):
            # `resource` is for metadata that points at an XML resource (Samsung's S Pen
            # RemoteAction table, for one); everything else uses a literal `value`.
            if meta.get("resource") is not None:
                lines.append(
                    f'            <meta-data android:name="{_esc(meta["name"])}"'
                    f' android:resource="{_esc(meta["resource"])}" />'
                )
            else:
                lines.append(
                    f'            <meta-data android:name="{_esc(meta["name"])}"'
                    f' android:value="{_esc(meta["value"])}" />'
                )
        for intent_filter in _as_list(activity.get("intent_filter")):
            lines.append("            <intent-filter>")
            for action in intent_filter.get("actions", []):
                lines.append(f'                <action android:name="{_esc(action)}" />')
            for category in intent_filter.get("categories", []):
                lines.append(f'                <category android:name="{_esc(category)}" />')
            for data in intent_filter.get("data", []):
                data_attrs = " ".join(
                    f'{attr}="{_esc(data[key])}"' for key, attr in DATA_ATTRS if data.get(key) is not None
                )
                lines.append(f"                <data {data_attrs} />")
            lines.append("            </intent-filter>")
        lines.append("        </activity>")

    lines.append("    </application>")
    lines.append("</manifest>")
    return "\n".join(lines) + "\n"


def build_gradle(namespace, min_sdk, target_sdk, code, version):
    """The single-module root build.gradle (see the module docstring for the layout)."""
    return f"""// Generated by artcraft-android-builder. cargo-ndk has already placed the native
// library into ../jniLibs; this project packages it with the Java Activity, the resources
// and ../AndroidManifest.xml, signed with the builder's keystore passed in through the
// ARTCRAFT_KEYSTORE* environment variables.

plugins {{
    id 'com.android.application' version '{GRADLE_PLUGIN_VERSION}'
}}

android {{
    namespace '{_groovy(namespace)}'
    compileSdk {target_sdk}

    defaultConfig {{
        applicationId '{_groovy(namespace)}'
        minSdk {min_sdk}
        targetSdk {target_sdk}
        // Mirrors ndk-build2's VersionCode so the Updater accepts upgrades from cargo-apk
        // builds: (1 << 24) | major << 16 | minor << 8 | patch.
        versionCode {code}
        versionName '{_groovy(version)}'
    }}

    sourceSets {{
        // Everything but the native library lives one level up, beside this project:
        // the launcher generator writes the manifest and java tree, cargo-ndk jniLibs.
        main {{
            manifest.srcFile '../AndroidManifest.xml'
            java.srcDirs = ['../java']
            res.srcDirs = ['../res']
            jniLibs.srcDirs = ['../jniLibs']
        }}
    }}

    signingConfigs {{
        builder {{
            def keystore = System.getenv('ARTCRAFT_KEYSTORE')
            if (keystore != null) {{
                storeFile file(keystore)
                storePassword System.getenv('ARTCRAFT_KEYSTORE_PASSWORD')
                keyAlias System.getenv('ARTCRAFT_KEY_ALIAS')
                keyPassword System.getenv('ARTCRAFT_KEY_PASSWORD')
            }}
        }}
    }}

    buildTypes {{
        release {{
            if (System.getenv('ARTCRAFT_KEYSTORE') != null) {{
                signingConfig signingConfigs.builder
            }}
        }}
        debug {{
            if (System.getenv('ARTCRAFT_KEYSTORE') != null) {{
                signingConfig signingConfigs.builder
            }}
        }}
    }}

    compileOptions {{
        sourceCompatibility JavaVersion.VERSION_17
        targetCompatibility JavaVersion.VERSION_17
    }}

    packaging {{
        jniLibs {{
            // cargo-ndk links the libraries uncompressed and page-aligned; load them
            // straight out of the APK instead of extracting and re-compressing.
            useLegacyPackaging = false
        }}
    }}
}}

dependencies {{
    // AndroidX pulls kotlin-stdlib 1.8 next to the old split -jdk7/-jdk8 artifacts; align
    // them (same combination the reference project ships).
    implementation platform('org.jetbrains.kotlin:kotlin-bom:1.8.22')
    implementation 'androidx.appcompat:appcompat:1.7.0'
    implementation 'androidx.core:core:1.13.1'
    // The Java half of GameActivity, whose Activity the launcher extends; version matched
    // to the vendored android-activity crate's game-activity backend (see its README).
    implementation 'androidx.games:games-activity:4.4.0'
}}
"""


def settings_gradle(app):
    return f"""// Generated by artcraft-android-builder.
pluginManagement {{
    repositories {{
        google()
        mavenCentral()
        gradlePluginPortal()
    }}
}}
dependencyResolutionManagement {{
    repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)
    repositories {{
        google()
        mavenCentral()
    }}
}}
rootProject.name = '{_groovy(app)}-android'
"""


def main(argv):
    if len(argv) != 5:
        raise SystemExit("usage: android_project.py ROOT ANDROID_DIR APP APP_VERSION")
    root, android_dir, app, version = Path(argv[1]), Path(argv[2]), argv[3], argv[4]

    cargo_meta = tomllib.loads((android_dir / "Cargo.toml").read_text())
    android_meta = cargo_meta["package"]["metadata"]["android"]
    sdk = android_meta.get("sdk") or {}
    min_sdk = int(sdk.get("min_sdk_version", 21))
    target_sdk = int(sdk.get("target_sdk_version", min_sdk))
    code = version_code(version)

    (android_dir / "AndroidManifest.xml").write_text(manifest_xml(android_meta))

    themes = android_dir / "res" / "values" / "themes.xml"
    themes.parent.mkdir(parents=True, exist_ok=True)
    themes.write_text(THEMES_XML)

    gradle_dir = android_dir / "android"
    gradle_dir.mkdir(parents=True, exist_ok=True)
    (gradle_dir / "settings.gradle").write_text(settings_gradle(app))
    (gradle_dir / "build.gradle").write_text(
        build_gradle(android_meta["package"], min_sdk, target_sdk, code, version)
    )
    (gradle_dir / "gradle.properties").write_text(GRADLE_PROPERTIES)

    # The wrapper (gradlew + jar + 8.11.1 properties); chmod because the copy may come from
    # a checkout that never had the bit set.
    shutil.copytree(root / "templates" / "gradle", gradle_dir, dirs_exist_ok=True)
    gradlew = gradle_dir / "gradlew"
    gradlew.chmod(gradlew.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    # Read by build-common.sh: cargo-ndk's --platform must agree with the APK's minSdk.
    (android_dir / ".artcraft-gradle.properties").write_text(f"MIN_SDK={min_sdk}\n")


if __name__ == "__main__":
    main(sys.argv)
