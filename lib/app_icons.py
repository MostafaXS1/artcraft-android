"""Launcher icons for every ArtCraft app, in one place.

Both callers — the generated-launcher heredoc in lib/build-common.sh and photocraft's
adapters/photocraft/prepare.sh — produce the same set of resources:

  res/mipmap-<density>/ic_launcher.png     legacy icons (file managers, pre-26 launchers)
  res/mipmap-anydpi-v26/ic_launcher.xml    adaptive icon: background / foreground / monochrome
  res/mipmap-anydpi-v26/ic_launcher_round.xml   ...same layers, for round launchers
  res/drawable/ic_launcher_background.xml  the solid brand colour, as a vector
  res/drawable-xxxhdpi/ic_launcher_foreground.png  the artwork, background stripped, on a
                                            transparent 108dp canvas inside the safe zone

The adaptive split is what modern launchers want: the background fills whatever shape the
launcher masks the icon into (circle, squircle, rounded square), the foreground carries the
artwork, and the `<monochrome>` layer gives Android 13+ themed icons a clean artwork
silhouette to tint — instead of tinting a whole white square the way a flat legacy PNG does.

The foreground raster is the app's own icon with its solid background flood-filled away from
the edges, so the silhouette is the artwork itself. The artwork is then scaled to the same
66.56/108 ratio (of the 108dp adaptive canvas) a hand-built adaptive icon uses, which keeps
it inside the launcher's visible safe zone.

Requires Python 3 (with Pillow) like the rest of the builder; ImageMagick is used to
rasterise SVG sources and for legacy resizes when present.
"""

import sys
from pathlib import Path

DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
# Adaptive-icon canvas is 108dp; the launcher guarantees the central 72dp circle is visible.
# A 66.56dp artwork (the scale a hand-built WordCraft icon uses) sits safely inside it.
CANVAS_PX = 432  # 108dp at xxxhdpi
ARTWORK_PX = round(CANVAS_PX * 66.56 / 108)
WORK_PX = 512  # raster working size before flood-fill/trim
FLOOD_THRESH = 45  # sum-of-bands tolerance for "same colour as the background"

_BG_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Launcher background layer: the app's brand colour, generated by lib/app_icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="{color}" android:pathData="M0,0h108v108h-108z" />
</vector>
"""

_ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Adaptive launcher icon, generated by lib/app_icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
"""


def _pillow():
    try:
        from PIL import Image, ImageDraw  # noqa: F401
    except ImportError:
        raise SystemExit("Adaptive launcher icons require Pillow (pip install pillow).")
    return Image, ImageDraw


def _magick():
    import shutil

    return shutil.which("magick") or shutil.which("convert")


def _rsvg():
    import shutil

    return shutil.which("rsvg-convert")


def pick_source(src: Path, app: str, explicit: Path = None) -> Path:
    """The artwork the icon is built from: an explicit -appicon, else the app's own
    largest master PNG (crisp 1024x1024 / 512x512), else its vector source."""
    if explicit:
        if not explicit.is_file():
            raise SystemExit(f"App icon not found: {explicit}")
        return explicit
    icon_dir = src / "assets" / "app-icon"
    if icon_dir.is_dir():
        # Prefer the app's own high-res PNG (master 1024x1024 or 512x512). These are
        # pristine renders produced for distribution. Using them directly avoids
        # ImageMagick MSVG clipPath bugs and huge memory allocation.
        pngs = [p for p in icon_dir.rglob("*.png") if app in p.name.lower()]
        high_res = [p for p in pngs if "1024" in p.name or "512" in p.name]
        if high_res:
            return max(high_res, key=lambda p: p.stat().st_size)
        # Vector sources if no high-res PNG is available
        svgs = [icon_dir / f"{app}.svg", icon_dir / "icon.svg"]
        svgs += sorted(p for p in icon_dir.glob("*.svg") if "-small" not in p.stem)
        rasterizer = _rsvg() or _magick()
        if rasterizer:
            for svg in svgs:
                if svg.is_file():
                    return svg
        # Any other own PNGs
        if pngs:
            return max(pngs, key=lambda p: p.stat().st_size)
    raise SystemExit(
        f"Could not find an app icon for {app} under assets/app-icon; "
        f"pass -appicon=<path> or create a custom adapter."
    )


def _raster(source: Path):
    """The icon as a WORK_PX RGBA raster, plus the un-flooded original for legacy sizes."""
    Image, _ = _pillow()
    work = Image.new("RGBA", (WORK_PX, WORK_PX))
    if source.suffix.lower() == ".svg":
        rsvg = _rsvg()
        magick = _magick()
        if not rsvg and not magick:
            raise SystemExit(f"Rasterising {source.name} needs rsvg-convert or ImageMagick.")
        import subprocess
        import tempfile

        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "raster.png"
            if rsvg:
                subprocess.run(
                    [rsvg, "-w", str(WORK_PX), "-h", str(WORK_PX), "-f", "png", "-o", str(out), str(source)],
                    check=True,
                )
            else:
                subprocess.run(
                    # `-background none` first, or ImageMagick flattens the SVG onto an opaque
                    # white canvas: a source drawn inside a clip (a rounded-square tile, like
                    # SoundCraft's) has transparent corners, and those corners then come back
                    # white — which both makes the brand-colour sampling below read white and
                    # leaves white wedges behind the launcher's mask.
                    [magick, "-background", "none", str(source), "-resize", f"{WORK_PX}x{WORK_PX}", str(out)],
                    check=True,
                )
            work = Image.open(out).convert("RGBA")
            work.load()
    else:
        work = Image.open(source).convert("RGBA")
        work.load()
    if work.size != (WORK_PX, WORK_PX):
        work = work.resize((WORK_PX, WORK_PX), Image.LANCZOS)
    return work


def _background_color(Image, im) -> str:
    """The icon's brand colour: the dominant opaque border colour, falling back to the
    dominant opaque colour of the whole artwork (icons that float on transparency), then
    to white."""
    from collections import Counter

    px = im.load()
    step = max(1, WORK_PX // 64)
    border = [
        px[x, 0][0:3] + (px[x, 0][3],)
        for x in range(0, WORK_PX, step)
    ] + [
        px[x, WORK_PX - 1][0:3] + (px[x, WORK_PX - 1][3],)
        for x in range(0, WORK_PX, step)
    ] + [
        px[0, y][0:3] + (px[0, y][3],)
        for y in range(0, WORK_PX, step)
    ] + [
        px[WORK_PX - 1, y][0:3] + (px[WORK_PX - 1, y][3],)
        for y in range(0, WORK_PX, step)
    ]
    opaque = [p[:3] for p in border if p[3] > 200]
    if len(opaque) >= len(border) * 0.3:
        colors = opaque
    else:
        colors = [
            px[x, y][0:3]
            for y in range(0, WORK_PX, step)
            for x in range(0, WORK_PX, step)
            if px[x, y][3] > 200
        ]
    if not colors:
        return "#FFFFFF"
    (r, g, b), _count = Counter(colors).most_common(1)[0]
    return f"#{r:02X}{g:02X}{b:02X}"


def _strip_background(im, pristine):
    """Flood-fill the solid background away from the artwork, seeded at the edges, and
    return the artwork on transparency. Icons whose background cannot be separated (the
    colour reaches no edge region) come back untouched."""
    Image, ImageDraw = _pillow()
    from collections import Counter

    # Crop transparent padding if any, so the squircle edges touch WORK_PX
    box = im.split()[3].getbbox()
    if box and (box[0] > 0 or box[1] > 0 or box[2] < im.width or box[3] < im.height):
        im = im.crop(box).resize((WORK_PX, WORK_PX), Image.LANCZOS)
        pristine = im.copy()

    px = im.load()
    # Remember the untouched colours: a pixel must only be cleared when it *was* the
    # background colour, never when the flood bled into the artwork.
    original = im.copy().load()
    before = sum(
        1
        for y in range(0, WORK_PX, 4)
        for x in range(0, WORK_PX, 4)
        if px[x, y][3] < 30
    )
    # The background colour to remove: the most common opaque colour on the border. A pixel
    # is only cleared when it matches *that colour*, so a flood that bleeds into the artwork
    # (SoundCraft's bird reaches the bottom and right edges, past its rounded clip) leaves the
    # artwork alone instead of erasing it. Sample slightly inset (offset=2) to avoid 1px
    # antialiased outer fringes.
    offset = 2
    border = [
        px[x, y][0:3]
        for y in range(0, WORK_PX, 2)
        for x in (offset, WORK_PX - 1 - offset)
        if px[x, y][3] > 150
    ] + [
        px[x, y][0:3]
        for x in range(0, WORK_PX, 2)
        for y in (offset, WORK_PX - 1 - offset)
        if px[x, y][3] > 150
    ]
    if not border:
        return pristine, False
    (br, bg, bb), _n = Counter(border).most_common(1)[0]

    def is_background(p) -> bool:
        return p[3] > 100 and abs(p[0] - br) + abs(p[1] - bg) + abs(p[2] - bb) <= FLOOD_THRESH

    # Flood a scratch copy and mark what it reached, so near-sentinel antialiasing cannot be
    # mistaken for the sentinel itself.
    sentinel = (255, 0, 255, 255)
    scratch = im.copy()
    spx = scratch.load()
    q = WORK_PX // 4
    seeds = [
        (0, 0),
        (WORK_PX - 1, 0),
        (0, WORK_PX - 1),
        (WORK_PX - 1, WORK_PX - 1),
        (offset, offset),
        (WORK_PX - 1 - offset, offset),
        (offset, WORK_PX - 1 - offset),
        (WORK_PX - 1 - offset, WORK_PX - 1 - offset),
        (WORK_PX // 2, offset),
        (WORK_PX // 2, WORK_PX - 1 - offset),
        (offset, WORK_PX // 2),
        (WORK_PX - 1 - offset, WORK_PX // 2),
        (q, offset),
        (3 * q, offset),
        (q, WORK_PX - 1 - offset),
        (3 * q, WORK_PX - 1 - offset),
        (offset, q),
        (offset, 3 * q),
        (WORK_PX - 1 - offset, q),
        (WORK_PX - 1 - offset, 3 * q),
    ]
    for seed in seeds:
        ImageDraw.floodfill(scratch, seed, sentinel, thresh=FLOOD_THRESH)
    for y in range(WORK_PX):
        for x in range(WORK_PX):
            if spx[x, y] == sentinel and (is_background(original[x, y]) or original[x, y][3] < 100):
                px[x, y] = (0, 0, 0, 0)
    after = sum(
        1
        for y in range(0, WORK_PX, 4)
        for x in range(0, WORK_PX, 4)
        if px[x, y][3] < 30
    )
    if (after - before) * 16 < WORK_PX * WORK_PX * 0.03:
        # Nothing separable was removed; keep the artwork as-is (a full-bleed icon).
        return pristine, False
    return im, True


def _foreground(Image, stripped) -> "Image":
    """The artwork trimmed to its bounds and centred on a transparent CANVAS_PX canvas."""
    box = stripped.split()[3].getbbox()
    art = stripped.crop(box) if box else stripped
    scale = min(ARTWORK_PX / art.width, ARTWORK_PX / art.height)
    art = art.resize(
        (max(1, round(art.width * scale)), max(1, round(art.height * scale))),
        Image.LANCZOS,
    )
    canvas = Image.new("RGBA", (CANVAS_PX, CANVAS_PX), (0, 0, 0, 0))
    canvas.paste(art, ((CANVAS_PX - art.width) // 2, (CANVAS_PX - art.height) // 2), art)
    return canvas


def _write_legacy(source: Path, work, res_dir: Path) -> None:
    """The flat density icons file managers and non-adaptive surfaces still read."""
    Image, _ = _pillow()
    base = work
    if source.suffix.lower() != ".svg":
        try:
            base = Image.open(source).convert("RGBA")
        except Exception:
            base = work

    for density, size in DENSITIES.items():
        out_dir = res_dir / f"mipmap-{density}"
        out_dir.mkdir(parents=True, exist_ok=True)
        out_png = out_dir / "ic_launcher.png"
        base.resize((size, size), Image.LANCZOS).save(out_png)


def generate(src: Path, app: str, res_dir: Path, explicit: Path = None) -> Path:
    """Build every launcher-icon resource for `app` into `res_dir`; return the source
    artwork that was used."""
    Image, _ = _pillow()
    source = pick_source(src, app, explicit)
    work = _raster(source)
    color = _background_color(Image, work)
    pristine = work.copy()
    stripped, _changed = _strip_background(work, pristine=pristine)
    foreground = _foreground(Image, stripped)

    # The flat density icons keep the artwork exactly as it looks today (background
    # included); only the adaptive foreground gets the background stripped away.
    _write_legacy(source, pristine, res_dir)
    (res_dir / "drawable").mkdir(parents=True, exist_ok=True)
    (res_dir / "drawable" / "ic_launcher_background.xml").write_text(
        _BG_XML.format(color=color)
    )
    (res_dir / "drawable-xxxhdpi").mkdir(parents=True, exist_ok=True)
    foreground.save(res_dir / "drawable-xxxhdpi" / "ic_launcher_foreground.png")
    anydpi = res_dir / "mipmap-anydpi-v26"
    anydpi.mkdir(parents=True, exist_ok=True)
    (anydpi / "ic_launcher.xml").write_text(_ADAPTIVE_XML)
    (anydpi / "ic_launcher_round.xml").write_text(_ADAPTIVE_XML)
    return source


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Generate ArtCraft launcher icons.")
    parser.add_argument("--src", required=True, help="App source checkout root")
    parser.add_argument("--app", required=True, help="App name")
    parser.add_argument("--dest", required=True, help="Android res/ directory to write into")
    parser.add_argument("--appicon", default="", help="Explicit icon file (-appicon)")
    args = parser.parse_args()
    chosen = generate(
        Path(args.src), args.app, Path(args.dest), Path(args.appicon) if args.appicon else None
    )
    try:
        shown = chosen.relative_to(Path(args.src))
    except ValueError:
        shown = chosen
    print(f"  Icon: {shown} (adaptive layers + density mipmaps)")
