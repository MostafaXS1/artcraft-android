#!/usr/bin/env bash
set -Eeuo pipefail
APP="${1:-tracedraw}"
TITLE="${2:-TraceDraw}"
SRC="${3:-source/tracedraw}"
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)"
SRC_ABS="$ROOT/$SRC"
ADAPTER="$ROOT/adapters/tracedraw"
DEST="$SRC_ABS/apps/$APP-android"

if ! grep -q '"apps/tracedraw-android"' "$SRC_ABS/Cargo.toml"; then
    sed -i 's/"apps\/tracedraw",/"apps\/tracedraw",\n    "apps\/tracedraw-android",/' "$SRC_ABS/Cargo.toml"
fi

# Expose upstream android module and entrypoint
sed -i 's/^mod android;/pub mod android;/' "$SRC_ABS/apps/tracedraw/src/lib.rs"
python3 - "$SRC_ABS/apps/tracedraw/src/android.rs" <<'PY'
import sys
from pathlib import Path
p = Path(sys.argv[1])
s = p.read_text()
s = s.replace("#[no_mangle]\nfn android_main(", "pub fn android_main(")
s = s.replace("#[no_mangle]\r\nfn android_main(", "pub fn android_main(")
p.write_text(s)
PY

mkdir -p "$DEST"
cp -a "$ADAPTER/." "$DEST/"
rm -f "$DEST/prepare.sh" "$DEST/README.md"
cp -f "$ROOT/templates/android/system_fonts.rs" "$DEST/src/system_fonts.rs"

python3 "$ROOT/lib/app_icons.py" --src "$SRC_ABS" --app "$APP" --dest "$DEST/res" || true
printf 'Generated by artcraft-android-builder; custom adapter sourced from adapters/tracedraw.\n' > "$DEST/.artcraft-android-builder-generated"

python3 - "$DEST/Cargo.toml" "$ROOT" "$APP" <<'PY'
from pathlib import Path
import sys, tomllib
path, root, app = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
sys.path.insert(0, str(root / "lib"))
import file_associations
file_associations.patch_cargo_toml(path, app)
tomllib.loads(path.read_text())
PY
echo "Installed TraceDraw adapter in $DEST"
