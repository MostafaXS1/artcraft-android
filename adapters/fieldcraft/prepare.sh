#!/usr/bin/env bash
set -Eeuo pipefail
APP="${1:-fieldcraft}"
TITLE="${2:-FieldCraft}"
SRC="${3:-source/fieldcraft}"
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)"
SRC_ABS="$ROOT/$SRC"
ADAPTER="$ROOT/adapters/fieldcraft"
DEST="$SRC_ABS/apps/$APP-android"

# FieldCraft uses SolidCraft's UI kit and vendored egui stack (egui 0.37 with FrameCompositor)
if [[ ! -d "$ROOT/source/solidcraft/vendor/egui" ]]; then
    echo "SolidCraft source with vendored egui not found, checking it out..."
    bash "$ROOT/build.sh" -solidcraft --noupdate || true
fi

if [[ -d "$ROOT/source/solidcraft/vendor/egui" ]]; then
    echo "Copying SolidCraft vendored egui stack into FieldCraft..."
    rm -rf "$SRC_ABS/vendor/egui"
    cp -a "$ROOT/source/solidcraft/vendor/egui" "$SRC_ABS/vendor/egui"
fi

python3 - "$SRC_ABS/Cargo.toml" <<'PY'
from pathlib import Path
import sys, re, tomllib
p = Path(sys.argv[1])
s = p.read_text()

# Update [workspace.dependencies] egui-winit if needed
s = re.sub(r'egui-winit\s*=\s*\{.*?path\s*=\s*"[^"]+".*?\}', 'egui-winit = { path = "vendor/egui/crates/egui-winit" }', s)

# Ensure exclude = ["vendor"] is in [workspace] so vendor/egui is treated as its own workspace root
if 'exclude' not in s:
    s = re.sub(r'(members\s*=\s*\[[^\]]+\])', r'\1\nexclude = ["vendor"]', s, count=1)

header = "[patch.crates-io]"
egui_patches = """
ecolor = { path = "vendor/egui/crates/ecolor" }
eframe = { path = "vendor/egui/crates/eframe" }
egui = { path = "vendor/egui/crates/egui" }
egui-wgpu = { path = "vendor/egui/crates/egui-wgpu" }
egui-winit = { path = "vendor/egui/crates/egui-winit" }
"""

if header in s:
    parts = s.split(header, 1)
    next_sec = re.search(r'\n\[', parts[1])
    patch_sec = parts[1][:next_sec.start()] if next_sec else parts[1]
    rest = parts[1][next_sec.start():] if next_sec else ""
    for crate in ("egui", "eframe", "epaint", "ecolor", "emath", "egui-wgpu", "egui-winit"):
        patch_sec = re.sub(rf'^\s*{crate}\s*=\s*\{{.*?\}}.*?\n?', '', patch_sec, flags=re.M)
    s = parts[0] + header + egui_patches + patch_sec.lstrip('\n') + rest
else:
    s = s.rstrip() + "\n\n" + header + egui_patches + "\n"

# Remove any [patch."https://github.com/storytold/egui.git"] section
git_header = '[patch."https://github.com/storytold/egui.git"]'
if git_header in s:
    parts = s.split(git_header)
    before = parts[0]
    after = parts[1]
    next_section = re.search(r'\n\[', after)
    after = after[next_section.start():] if next_section else ''
    s = before + after

tomllib.loads(s)
p.write_text(s)
print("workspace: configured SolidCraft vendored egui patches in FieldCraft Cargo.toml")
PY

mkdir -p "$DEST"
cp -a "$ADAPTER/." "$DEST/"
rm -f "$DEST/prepare.sh" "$DEST/README.md"
cp -f "$ROOT/templates/android/system_fonts.rs" "$DEST/src/system_fonts.rs"
cp -f "$ROOT/templates/android/mobile_text_bar.rs" "$DEST/src/mobile_text_bar.rs"
cp -f "$ROOT/templates/android/touch_gestures.rs" "$DEST/src/touch_gestures.rs"

python3 "$ROOT/lib/app_icons.py" --src "$SRC_ABS" --app "$APP" --dest "$DEST/res" || true
printf 'Generated by artcraft-android-builder; custom adapter sourced from adapters/fieldcraft.\n' > "$DEST/.artcraft-android-builder-generated"

python3 - "$DEST/Cargo.toml" "$ROOT" "$APP" <<'PY'
from pathlib import Path
import sys, tomllib
path, root, app = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
sys.path.insert(0, str(root / "lib"))
import file_associations
file_associations.patch_cargo_toml(path, app)
tomllib.loads(path.read_text())
PY

echo "FieldCraft prepare.sh complete"
