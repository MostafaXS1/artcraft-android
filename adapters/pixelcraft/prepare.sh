#!/usr/bin/env bash
set -Eeuo pipefail
APP="${1:-pixelcraft}"
TITLE="${2:-PixelCraft}"
SRC="${3:-source/pixelcraft}"
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)"
SRC_ABS="$ROOT/$SRC"
ADAPTER="$ROOT/adapters/pixelcraft"
DEST="$SRC_ABS/apps/$APP-android"

# Add workspace to root manifest if missing and update rfd to 0.17
python3 - "$SRC_ABS/Cargo.toml" <<'PY'
from pathlib import Path
import re, sys
p = Path(sys.argv[1])
s = p.read_text()
s = re.sub(r'(?m)^(\s*rfd\s*=\s*)"[^"]+"', r'\1"0.17"', s)
s = s.replace(
    '[target.\'cfg(any(target_os = "linux", target_os = "macos"))\'.dependencies]',
    '[target.\'cfg(any(target_os = "linux", target_os = "macos", target_os = "android"))\'.dependencies]',
)
if "[workspace]" not in s:
    s = '[workspace]\nmembers = [".", "apps/pixelcraft-android"]\n\n' + s
else:
    m = re.search(r'(?ms)^members\s*=\s*\[(.*?)\]', s)
    if m:
        inner = m.group(1)
        if '"apps/pixelcraft-android"' not in inner:
            new_inner = inner.rstrip()
            if not new_inner.endswith(','):
                new_inner += ','
            new_inner += ' "apps/pixelcraft-android"'
            s = s[:m.start(1)] + new_inner + s[m.end(1):]
p.write_text(s)
PY

# Adapt PixelCraft so its main application can be loaded by the Android cdylib
python3 - "$SRC_ABS" <<'PY'
from pathlib import Path
import sys

src = Path(sys.argv[1])
lib_p = src / "src" / "lib.rs"
main_p = src / "src" / "main.rs"
prod_p = src / "src" / "productivity_ui.rs"

if prod_p.is_file():
    prod_s = prod_p.read_text()
    if "pub(super) fn open_recent(" in prod_s:
        prod_s = prod_s.replace("pub(super) fn open_recent(", "pub fn open_recent(")
        prod_p.write_text(prod_s)

main_s = main_p.read_text()
if "pixelcraft::run_desktop" not in main_s and "pub fn run_desktop" not in main_s:
    lib_s = lib_p.read_text()
    header = "extern crate self as pixelcraft;\n\n" + lib_s + "\n\n"

    body = main_s
    # Remove inner attribute
    body = body.replace('#![cfg_attr(\n    all(target_os = "windows", not(debug_assertions)),\n    windows_subsystem = "windows"\n)]\n', '')

    old_use = '''use pixelcraft::{
    extensions::{self, Manager},
    formats,
    model::*,
    updates::{self, AboutInfo, INSTALLED_VERSION, Release},
};'''

    new_use = '''use crate::{
    extensions::Manager,
    model::*,
    updates::{AboutInfo, INSTALLED_VERSION, Release},
};'''

    body = body.replace(old_use, new_use)
    body = body.replace("struct PixelCraft {", "pub struct PixelCraft {", 1)
    body = body.replace("    fn new(cc: &eframe::CreationContext", "    pub fn new(cc: &eframe::CreationContext", 1)
    body = body.replace("fn main() -> eframe::Result {", "pub fn run_desktop() -> eframe::Result {", 1)

    lib_p.write_text(header + body)

    new_main = """fn main() -> eframe::Result {
    pixelcraft::run_desktop()
}
"""
    main_p.write_text(new_main)
    print("Adapted PixelCraft src/lib.rs and src/main.rs for Android library integration")
PY

mkdir -p "$DEST"
cp -a "$ADAPTER/." "$DEST/"
rm -f "$DEST/prepare.sh" "$DEST/README.md"
cp -f "$ROOT/templates/android/system_fonts.rs" "$DEST/src/system_fonts.rs"
cp -f "$ROOT/templates/android/mobile_text_bar.rs" "$DEST/src/mobile_text_bar.rs"
cp -f "$ROOT/templates/android/touch_gestures.rs" "$DEST/src/touch_gestures.rs"
sed -i '/source: egui::MouseWheelSource::/d' "$DEST/src/touch_gestures.rs" 2>/dev/null || true
[[ -f "$ADAPTER/src/mcp_http.rs" ]] || cp -f "$ROOT/templates/android/mcp_http.rs" "$DEST/src/mcp_http.rs"

python3 "$ROOT/lib/app_icons.py" --src "$SRC_ABS" --app "$APP" --dest "$DEST/res" || true
printf 'Generated by artcraft-android-builder; custom adapter sourced from adapters/pixelcraft.\n' > "$DEST/.artcraft-android-builder-generated"

python3 - "$DEST/Cargo.toml" "$ROOT" "$APP" <<'PY'
from pathlib import Path
import sys, tomllib
path, root, app = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
sys.path.insert(0, str(root / "lib"))
import file_associations
file_associations.patch_cargo_toml(path, app)
tomllib.loads(path.read_text())
PY
echo "Installed PixelCraft adapter in $DEST"
