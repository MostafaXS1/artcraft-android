#!/usr/bin/env bash
set -Eeuo pipefail
APP="${1:-anicraft}"
TITLE="${2:-AniCraft}"
SRC="${3:-source/anicraft}"
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)"
SRC_ABS="$ROOT/$SRC"
ADAPTER="$ROOT/adapters/anicraft"
DEST="$SRC_ABS/apps/$APP-android"

# Remove accesskit from eframe in Cargo.toml for Android native-activity compatibility
sed -i 's/"accesskit",\?//g' "$SRC_ABS/Cargo.toml" || true

# Add apps/anicraft-android to workspace members
python3 - "$SRC_ABS/Cargo.toml" <<'PY'
from pathlib import Path
import re, sys
p = Path(sys.argv[1])
s = p.read_text()
m = re.search(r'(?ms)^members\s*=\s*\[(.*?)\]', s)
if m:
    inner = m.group(1)
    if '"apps/anicraft-android"' not in inner:
        new_inner = inner.rstrip()
        if not new_inner.endswith(','):
            new_inner += ','
        new_inner += ' "apps/anicraft-android"'
        s = s[:m.start(1)] + new_inner + s[m.end(1):]
        p.write_text(s)
PY

# Ensure source/anicraft has a [lib] entry
if ! grep -q '^\[lib\]' "$SRC_ABS/Cargo.toml"; then
    cat >> "$SRC_ABS/Cargo.toml" <<'EOF'

[lib]
name = "anicraft"
path = "src/lib.rs"
crate-type = ["rlib"]
EOF
fi

# Create source/anicraft/src/lib.rs dynamically based on modules in src/main.rs
python3 - "$SRC_ABS/src/main.rs" "$SRC_ABS/src/lib.rs" <<'PY'
import re, sys
from pathlib import Path

main_p = Path(sys.argv[1])
lib_p = Path(sys.argv[2])

main_text = main_p.read_text()

# Walk the file line by line and keep the attributes that sit on a module declaration.
# `#[macro_use]` on `mod i18n;` is what puts the `tr!`/`trn!`/`trc!` macros in scope for
# every module declared after it; dropping it (as a plain "mod name" scan would) leaves
# the whole crate without `tr!` and it fails to compile with "cannot find macro `tr`".
# `#[cfg(...)]` gates have to survive as well, or a platform-only module (the wasm-only
# `web`) would be compiled for Android.
mod_re = re.compile(r'^(?:pub\s+)?mod\s+([a-zA-Z0-9_]+)\s*;$')
# Attributes worth keeping: `#[macro_use]` and any `#[cfg(...)]` gate.
attr_re = re.compile(r'^#\[(?:macro_use|cfg\([^\n]*\))\]$')

lines = [
    "#![deny(clippy::unwrap_used, clippy::expect_used, clippy::panic)]",
    "",
]
pending_attrs = []
for raw in main_text.splitlines():
    line = raw.strip()
    if attr_re.match(line):
        pending_attrs.append(line)
        continue
    match = mod_re.match(line)
    if not match:
        # Any other item ends the attribute run (an attribute belongs to what follows it).
        pending_attrs = []
        continue
    name = match.group(1)
    attrs = pending_attrs
    pending_attrs = []
    if name.endswith("_tests"):
        # `#[cfg(test)]` modules: they belong to the desktop test runs, not to the
        # shipped library.
        continue
    for attr in attrs:
        lines.append(attr)
    lines.append(f"pub mod {name};")

lines.extend([
    "",
    "pub use app::App;",
    "pub use anicraft_engine::Session;",
    "",
    "use std::path::Path;",
    "",
    "pub fn open_session(file: Option<&Path>) -> Session {",
    "    let Some(p) = file else { return Session::new(anicraft_engine::doc::sample::demo()) };",
    "    let mut s = Session::default();",
    '    match s.execute("file.open", &serde_json::json!({"path": p.display().to_string()})) {',
    "        Ok(v) => {",
    '            if let Some(r) = v.get("report").and_then(|r| r.as_str()) {',
    '                println!("{r}");',
    "            }",
    "            s",
    "        }",
    "        Err(e) => {",
    '            eprintln!("could not open {}: {e}; starting with the sample", p.display());',
    "            Session::new(anicraft_engine::doc::sample::demo())",
    "        }",
    "    }",
    "}",
])

lib_p.write_text("\n".join(lines) + "\n")
PY

mkdir -p "$DEST"
cp -a "$ADAPTER/." "$DEST/"
rm -f "$DEST/prepare.sh" "$DEST/README.md"
cp -f "$ROOT/templates/android/system_fonts.rs" "$DEST/src/system_fonts.rs"
cp -f "$ROOT/templates/android/mobile_text_bar.rs" "$DEST/src/mobile_text_bar.rs"
cp -f "$ROOT/templates/android/touch_gestures.rs" "$DEST/src/touch_gestures.rs"
# Ensure java directory and AniCraftActivity.java exist
mkdir -p "$DEST/java/com/artcraft/anicraft"
python3 - "$ROOT/templates/android/SafActivity.java" "$DEST/java/com/artcraft/anicraft/AniCraftActivity.java" <<'PY'
from pathlib import Path
import sys
src = Path(sys.argv[1]).read_text()
dst = (
    src.replace("__PACKAGE__", "com.artcraft.anicraft")
    .replace("__CLASS__", "AniCraftActivity")
    .replace("__TAG__", "AniCraftActivity")
)
Path(sys.argv[2]).write_text(dst)
PY

python3 "$ROOT/lib/app_icons.py" --src "$SRC_ABS" --app "$APP" --dest "$DEST/res" || true
printf 'Generated by artcraft-android-builder; custom adapter sourced from adapters/anicraft.\n' > "$DEST/.artcraft-android-builder-generated"

# Bundle an ffmpeg for the video export.
#
# AniCraft's "Export video" runs an ffmpeg program: the `ANICRAFT_FFMPEG` environment
# variable, else `ffmpeg` from the PATH. Android has neither, so the export could not work
# at all ("install ffmpeg or point ANICRAFT_FFMPEG at it").
#
# The program is built for Android (arm64) by lib/ffmpeg_android.sh and dropped next to
# the app's native library: the platform extracts everything under lib/<abi>/ with the
# executable bit set, so the launcher can run it from there.
#
# It carries a ".so" name because that is what the packaging step keeps: a file under
# lib/<abi>/ that is not called "*.so" is left out of the APK.
echo "Bundling ffmpeg for the video export..."
FFMPEG_BUNDLE_NAME="libanicraft_ffmpeg.so"
FFMPEG_DIR="$DEST/extra-jniLibs/arm64-v8a"
mkdir -p "$FFMPEG_DIR"
bash "$ROOT/lib/ffmpeg_android.sh" "$FFMPEG_DIR" "$FFMPEG_BUNDLE_NAME"

# Keep the right-hand panel from growing without bound.
#
# The right-hand panel grew a little on every frame, until it reached its maximum: the
# sidebar expanded while the user drew, and a touch or a hold on the canvas kept the app
# drawing, so it looked like the sidebar grew whenever anything was touched.
#
# egui takes a panel's size from its content. The content of this panel is two scroll
# areas, and a scroll area's content is always a hair wider than the area it is laid out
# in (egui rounds the content rect up to whole pixels), so the panel's stored width grew
# by that fraction on every frame: the panel was a little wider each time, and its content
# a little wider again.
#
# On Android the panel therefore keeps the width it is given instead of following its
# content. The desktop build is untouched: there the panel still hugs its content and can
# be dragged.
python3 - "$SRC_ABS/src/app.rs" <<'PY'
from pathlib import Path
import sys

app = Path(sys.argv[1])
s = app.read_text()

old = 'egui::Panel::right("properties").resizable(true).default_size(dock_w).max_size((room.x * 0.5).max(220.0)).frame(egui::Frame::NONE.fill(T.panel).inner_margin(egui::Margin::same(0))).show(ui, |ui| panels::right(self, ui));'
new = '// Android: the panel keeps the width it is given. egui takes a panel\'s size from its\n        // content, and a scroll area\'s content is always a hair wider than the area it is\n        // laid out in (egui rounds the content rect up to whole pixels), so the panel grew a\n        // little on every frame until it reached its maximum — the sidebar expanded while the\n        // user drew or held a finger on the canvas.\n        #[cfg(not(target_os = "android"))]\n        egui::Panel::right("properties").resizable(true).default_size(dock_w).max_size((room.x * 0.5).max(220.0)).frame(egui::Frame::NONE.fill(T.panel).inner_margin(egui::Margin::same(0))).show(ui, |ui| panels::right(self, ui));\n        #[cfg(target_os = "android")]\n        egui::Panel::right("properties").exact_size(dock_w).frame(egui::Frame::NONE.fill(T.panel).inner_margin(egui::Margin::same(0))).show(ui, |ui| panels::right(self, ui));'

if new in s:
    print("the right panel is already pinned on Android")
elif old in s:
    app.write_text(s.replace(old, new, 1))
    print("pinned the right panel's width on Android")
else:
    print("NOT FOUND: the right panel")

PY

python3 - "$DEST/Cargo.toml" "$ROOT" "$APP" <<'PY'
from pathlib import Path
import sys, tomllib
path, root, app = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
sys.path.insert(0, str(root / "lib"))
import file_associations
file_associations.patch_cargo_toml(path, app)
tomllib.loads(path.read_text())
PY
echo "Installed AniCraft adapter in $DEST"
