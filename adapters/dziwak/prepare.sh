#!/usr/bin/env bash
set -Eeuo pipefail
APP="${1:-dziwak}"
TITLE="${2:-Dziwak}"
SRC="${3:-source/dziwak}"
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)"
SRC_ABS="$ROOT/$SRC"
ADAPTER="$ROOT/adapters/dziwak"
DEST="$SRC_ABS/apps/$APP-android"

# Update root Cargo.toml to add workspace member
python3 - "$SRC_ABS/Cargo.toml" <<'PY'
from pathlib import Path
import re, sys
p = Path(sys.argv[1])
s = p.read_text()
m = re.search(r'(?ms)^members\s*=\s*\[(.*?)\]', s)
if m:
    inner = m.group(1)
    if '"apps/dziwak-android"' not in inner:
        new_inner = inner.rstrip()
        if not new_inner.endswith(','):
            new_inner += ','
        new_inner += ' "apps/dziwak-android"'
        s = s[:m.start(1)] + new_inner + s[m.end(1):]
p.write_text(s)
PY

# Add [lib] to crates/app/Cargo.toml and create src/lib.rs
python3 - "$SRC_ABS/crates/app" <<'PY'
from pathlib import Path
import sys, re
app_dir = Path(sys.argv[1])
manifest = app_dir / "Cargo.toml"
s = manifest.read_text()
if "[lib]" not in s:
    s += '\n\n[lib]\nname = "dziwak"\npath = "src/lib.rs"\ncrate-type = ["rlib"]\n'
s = re.sub(r'eframe\s*=\s*\{[^}]*"wayland"[^}]*\}', 'eframe = { version = "0.33", default-features = false, features = ["glow", "default_fonts"] }', s)
s = re.sub(r'rfd\s*=\s*\{[^}]*\}', 'rfd = { path = "../../vendor/rfd", default-features = false }', s)
manifest.write_text(s)

lib_rs = app_dir / "src" / "lib.rs"
lib_code = """pub mod i18n;
pub mod i18n_table;
pub mod state;
pub mod theme;
pub mod ui;

impl eframe::App for state::DziwakApp {
    fn clear_color(&self, _visuals: &eframe::egui::Visuals) -> [f32; 4] {
        [0.149, 0.149, 0.149, 1.0]
    }

    fn update(&mut self, ctx: &eframe::egui::Context, frame: &mut eframe::Frame) {
        ui::render_app(self, ctx, frame);
    }
}
"""
lib_rs.write_text(lib_code)
PY

mkdir -p "$DEST"
cp -a "$ADAPTER/." "$DEST/"
rm -f "$DEST/prepare.sh" "$DEST/README.md"
rm -rf "$DEST/assets"
cp -f "$ROOT/templates/android/system_fonts.rs" "$DEST/src/system_fonts.rs"
python3 - "$DEST/src/system_fonts.rs" <<'PY'
from pathlib import Path
import sys, re
p = Path(sys.argv[1])
s = p.read_text()
s = re.sub(r'(?ms)pub fn install_system_fonts\(ctx: &egui::Context\) \{.*?^\}', 'pub fn install_system_fonts(_ctx: &egui::Context) {}', s)
p.write_text(s)
PY

cp -f "$ROOT/templates/android/mobile_text_bar.rs" "$DEST/src/mobile_text_bar.rs"
cp -f "$ROOT/templates/android/touch_gestures.rs" "$DEST/src/touch_gestures.rs"
sed -i -e '/source: egui::MouseWheelSource::/d' -e '/phase: TouchPhase::/d' "$DEST/src/touch_gestures.rs" 2>/dev/null || true
[[ -f "$ADAPTER/src/mcp_http.rs" ]] || cp -f "$ROOT/templates/android/mcp_http.rs" "$DEST/src/mcp_http.rs"

python3 "$ROOT/lib/app_icons.py" --src "$SRC_ABS" --app "$APP" --dest "$DEST/res" || true
printf 'Generated by artcraft-android-builder; custom adapter sourced from adapters/dziwak.\n' > "$DEST/.artcraft-android-builder-generated"

python3 - "$DEST/Cargo.toml" "$ROOT" "$APP" <<'PY'
from pathlib import Path
import sys, tomllib
path, root, app = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
sys.path.insert(0, str(root / "lib"))
import file_associations
file_associations.patch_cargo_toml(path, app)
tomllib.loads(path.read_text())
PY
echo "Installed Dziwak adapter in $DEST"
