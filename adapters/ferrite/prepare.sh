#!/usr/bin/env bash
set -Eeuo pipefail
APP="${1:-ferrite}"
TITLE="${2:-Ferrite}"
SRC="${3:-source/ferrite}"
ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)"
SRC_ABS="$ROOT/$SRC"
ADAPTER="$ROOT/adapters/ferrite"
DEST="$SRC_ABS/apps/$APP-android"

# Remove rust-toolchain.toml if present so the builder's Rust 1.99.0 is used
rm -f "$SRC_ABS/rust-toolchain" "$SRC_ABS/rust-toolchain.toml"

# Ensure root manifest is a workspace, uses rfd 0.17, and defines [lib]
python3 - "$SRC_ABS/Cargo.toml" <<'PY'
from pathlib import Path
import re, sys
p = Path(sys.argv[1])
s = p.read_text()
s = re.sub(r'(?m)^(\s*rfd\s*=\s*)"[^"]+"', r'\1"0.17"', s)

if "[workspace]" not in s:
    s = '[workspace]\nmembers = [".", "apps/ferrite-android"]\n\n' + s
else:
    m = re.search(r'(?ms)^members\s*=\s*\[(.*?)\]', s)
    if m:
        inner = m.group(1)
        if '"apps/ferrite-android"' not in inner:
            new_inner = inner.rstrip()
            if not new_inner.endswith(','):
                new_inner += ','
            new_inner += ' "apps/ferrite-android"'
            s = s[:m.start(1)] + new_inner + s[m.end(1):]

if "[lib]" not in s:
    s = s.rstrip() + '\n\n[lib]\nname = "ferrite"\npath = "src/lib.rs"\n'

p.write_text(s)
PY

# Create src/lib.rs if not present
if [[ ! -f "$SRC_ABS/src/lib.rs" ]]; then
    cat > "$SRC_ABS/src/lib.rs" <<'EOF'
rust_i18n::i18n!("locales", fallback = "en");

pub mod app;
pub mod config;
pub mod diag;
pub mod editor;
pub mod error;
pub mod export;
pub mod files;
pub mod fonts;
#[cfg(feature = "lsp")]
pub mod lsp;
#[cfg(not(feature = "lsp"))]
#[path = "lsp_stub.rs"]
pub mod lsp;
pub mod markdown;
pub mod path_utils;
pub mod platform;
pub mod preview;
pub mod single_instance;
#[cfg(feature = "spellcheck")]
pub mod spellcheck;
pub mod state;
pub mod string_utils;
pub mod terminal;
pub mod theme;
pub mod ui;
pub mod update;
pub mod util;
pub mod vcs;
#[cfg(feature = "async-workers")]
pub mod workers;
pub mod workspaces;

pub use app::FerriteApp;

pub fn purge_allocator_caches() {}
pub fn log_memory(_label: &str) {}
EOF
fi

# Vendor termios for Android support
rm -rf "$SRC_ABS/vendor/termios"
mkdir -p "$SRC_ABS/vendor"
cp -a "$ROOT/vendor/termios" "$SRC_ABS/vendor/termios"

python3 - "$SRC_ABS/Cargo.toml" <<'PY'
from pathlib import Path
import sys
p = Path(sys.argv[1])
s = p.read_text()
if "[patch.crates-io]" not in s:
    s += '\n[patch.crates-io]\ntermios = { path = "vendor/termios" }\n'
elif 'termios =' not in s:
    s = s.replace('[patch.crates-io]', '[patch.crates-io]\ntermios = { path = "vendor/termios" }')
p.write_text(s)
PY

# Guard video WebView on Android to use thumbnail fallback
python3 - "$SRC_ABS/src/markdown/video_render.rs" <<'PY'
from pathlib import Path
import sys
p = Path(sys.argv[1])
if p.exists():
    s = p.read_text()
    marker = "#[cfg(target_os = \"android\")]\n    return Err(());\n"
    if marker not in s:
        target = "if !is_valid_youtube_video_id(video_id) {\n        return Err(());\n    }"
        replacement = target + "\n\n    " + marker
        if target in s:
            p.write_text(s.replace(target, replacement, 1))
PY

mkdir -p "$DEST"
cp -a "$ADAPTER/." "$DEST/"
rm -f "$DEST/prepare.sh" "$DEST/README.md" "$DEST/src/touch_gestures.rs"
cp -f "$ROOT/templates/android/system_fonts.rs" "$DEST/src/system_fonts.rs"
cp -f "$ROOT/templates/android/mobile_text_bar.rs" "$DEST/src/mobile_text_bar.rs"
[[ -f "$ADAPTER/src/mcp_http.rs" ]] || cp -f "$ROOT/templates/android/mcp_http.rs" "$DEST/src/mcp_http.rs"

python3 "$ROOT/lib/app_icons.py" --src "$SRC_ABS" --app "$APP" --dest "$DEST/res" || true
printf 'Generated by artcraft-android-builder; custom adapter sourced from adapters/ferrite.\n' > "$DEST/.artcraft-android-builder-generated"

python3 - "$DEST/Cargo.toml" "$ROOT" "$APP" <<'PY'
from pathlib import Path
import sys, tomllib
path, root, app = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
sys.path.insert(0, str(root / "lib"))
import file_associations
file_associations.patch_cargo_toml(path, app)
tomllib.loads(path.read_text())
PY
echo "Installed Ferrite adapter in $DEST"
